import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { resolve, join } from 'node:path';
import { pathToFileURL } from 'node:url';

// Reproduce repository-owned native evidence through the public model.
// This generator does not launch Office or execute embedded content.
// Usage after build: node scripts/prepare-native-ppt-font-runs.mjs [OUTPUT] [DIST]
const output = resolve(process.argv[2] ?? '.native-validation/ppt-font-runs');
const dist = resolve(process.argv[3] ?? 'dist');
const { PptDocument } = await import(pathToFileURL(join(dist, 'index.js')).href);
const hash = bytes => createHash('sha256').update(bytes).digest('hex');
const source = new Uint8Array(readFileSync(new URL('../test/fixtures/ppt/native-text.ppt', import.meta.url)));
const sourceHash = '2bae7c1501262b79d2d9840ba968a5ed7b4ee12facde52082d3b114772f9b4e0';
const outputHash = '505d12c3569cba74b5b66a8df93960d1d0c1afdfdc33a598e73d06fcea24cc45';
if (hash(source) !== sourceHash) throw new Error('Owned native source differs from the retained PowerPoint case');
const document = new PptDocument(source), changes = [];
for (const [slideId, shapeName, expectedText, before, after] of [
  [256, 'FixtureTitle', 'Native title fixture', 28, 32],
  [257, 'FixtureUnicode', 'Unicode Ω fixture', 24, 30],
]) {
  const slides = document.slides.filter(slide => slide.slideId === slideId);
  const shapes = slides.length === 1 ? slides[0].shapes.filter(shape => shape.name === shapeName) : [];
  if (shapes.length !== 1 || shapes[0].texts.length !== 1) throw new Error('Native shape/text identity changed');
  const text = shapes[0].texts[0];
  if (text.text !== expectedText || text.runsStatus !== 'decoded' || text.runs.length !== 1) throw new Error('Native run model changed');
  const run = text.runs[0];
  if (run.start !== 0 || run.end !== text.text.length || run.directFontSizePoints !== before) throw new Error('Native literal slot changed');
  run.directFontSizePoints = after;
  changes.push({ slideId, shapeId: shapes[0].shapeId, shapeName, start: run.start, end: run.end, property: 'directFontSizePoints', before, after });
}
const edited = document.serialize();
if (hash(edited) !== outputHash) throw new Error('Output differs from the retained native-validated artifact; obtain new native evidence');
mkdirSync(output, { recursive: true });
writeFileSync(join(output, 'ppt-font-runs-before.ppt'), source);
writeFileSync(join(output, 'ppt-font-runs-edited.ppt'), edited);
const manifest = {
  provenance: 'Repository-owned native-text.ppt fixture; fixed existing two-byte character font-size slots only',
  nativeValidatedByThisRun: false,
  sourceSha256: sourceHash, outputSha256: outputHash,
  changedBytes: edited.reduce((count, byte, index) => count + Number(byte !== source[index]), 0),
  changes,
  evidenceLimits: ['Captured character fonts/text, geometry and notes only', 'No rendering/full-format fidelity claim', 'Native save/reopen compares against unchanged native save control; note shape IDs are regenerated by PowerPoint'],
};
writeFileSync(join(output, 'ppt-font-runs-manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`);
console.log(JSON.stringify(manifest));

